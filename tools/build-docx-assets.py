#!/usr/bin/env python3
"""Pack the files the Word export needs into js/docx-assets.js.

The site also runs straight from disk (file://), where the browser cannot fetch()
neighbouring files, so the .docx builder gets fonts and images from this script
instead. Re-run after changing any of the inputs:  python3 tools/build-docx-assets.py
"""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
b64 = lambda p: base64.b64encode((root / p).read_bytes()).decode('ascii')
assets = {
    # unaltered TH Sarabun New TTFs (Word embeds TrueType, not WOFF2)
    'fontRegular': b64('fonts/THSarabunNew-Regular.ttf'),
    'fontBold': b64('fonts/THSarabunNew-Bold.ttf'),
    'coverSvg': (root / 'assets/cover-bg.svg').read_text(encoding='utf-8'),
    'coverLogo': b64('assets/school-logo.png'),
    'garuda': b64('assets/garuda.png'),
}
out = root / 'js/docx-assets.js'
out.write_text('/* Generated by tools/build-docx-assets.py; do not edit. */\n'
               'window.DOCX_ASSETS = ' + json.dumps(assets, ensure_ascii=False) + ';\n', encoding='utf-8')
print(f'wrote {out.relative_to(root)} ({out.stat().st_size:,} bytes)')
